"""Author/reviewer handoff for independent data; never synthesizes reviewed cases."""
import argparse
from pathlib import Path
from .tasks import SCHEMAS
from .storage import atomic_json, atomic_write

INSTRUCTIONS = '''# Independent evaluation author/reviewer handoff

No cases or human approvals are generated by this script. Transfer scoring remains
unavailable until a separately authored and reviewed corpus is imported.

1. Author source documents independently of autonomous_learning.scenarios and the
   training renderer/templates. Use fictional data or explicitly approved data only.
2. Use all seven task output schemas in task_schemas.json. Keep family_id and
   template_family accurate and disjoint from training. Record authoring process,
   source provenance and any previous training/diagnostic exposure in a private ledger.
3. Cite exact document_id/page/start/end/quote spans. Use empty evidence for
   inventory-established absence and explicit relevant source_references paths.
4. Include valid controls, missing/unreadable/incomplete evidence, conditional
   unknowns, conflicting dates, correct abstention and unsupported-assertion traps.
5. Have a separate reviewer establish reference findings AND required supporting
   evidence, scope, offsets and review flags. Record reviewer identity/date and
   case hash in your review ledger; never infer review from a filename.
6. Keep development/probes/release cases and related families isolated. A release
   corpus is sealed and must not be forwarded to curriculum planning or generation.
7. Populate benchmark_import_contract.json with real authored cases and set
   independently_reviewed=true only after the recorded review actually occurs.
   Use the import-benchmark CLI; its family/template/content leakage checks apply.

For unfamiliar prose, grounded scoring requires reviewed evidence anchors. Without
review, semantic grounding is explicitly unavailable. Exact-reference scoring is
conservative about alternate phrasings. This kit is an authoring contract, not gold data.
'''


def prepare(directory):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    atomic_json(directory / 'task_schemas.json', SCHEMAS)
    atomic_json(directory / 'benchmark_import_contract.json', {
        'version': 1, 'tier': 'probes', 'process': 'independent', 'independently_reviewed': False, 'cases': []})
    atomic_json(directory / 'case_contract.json', {'required_case_fields': [
        'id', 'family_id', 'template_family', 'contract_version', 'task', 'payload', 'target'],
        'contract_version': 'document-verification-v1',
        'payload_fields': ['instruction', 'scenario', 'response_schema'],
        'scenario_fields': ['synthetic', 'claim_category', 'claim_facts', 'inventory', 'documents', 'fictional_rule_pack'],
        'review_ledger_fields': ['case_sha256', 'source_provenance', 'author', 'reviewer', 'reviewed_at',
                                 'finding_checked', 'evidence_relevance_checked', 'leakage_checked'],
        'status': 'requires external authorship and review; empty cases cannot be imported'})
    atomic_write(directory / 'REVIEW.md', INSTRUCTIONS)
    return {'directory': str(directory), 'cases_created': 0, 'transfer_scoring': 'unavailable'}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    print(prepare(args.output))


if __name__ == '__main__':
    main()
